function issue(store,description,overrides={},time=Date.now()) {
  return store.report({lab:'innovation',description,...overrides},time);
}
test('multilingual workstation clues and ambiguity',()=>{
  assert.equal(matchReport('শেষ সারি সিট ৫ বন্ধ হয়ে যায়').asset,'PC-17');
  assert.equal(matchReport('পিসি ১৭ বারবার বন্ধ হয়ে যায়').fault,'power');
  assert.equal(matchReport('PC 17 or PC 16 restart').asset,null);
  assert.equal(matchReport('PC 3 monitor blank','PC-04').asset,null);
  assert.equal(matchReport('monitor blank').fault,'display');
});
test('duplicates link, repair requires a note, and recurrence retains history',t=>{
  const store=fixture(t);
  const first=issue(store,'PC 17 keeps restarting and shuts down');
  assert.equal(first.action,'created');
  const linked=issue(store,'পিসি ১৭ বারবার বন্ধ হয়ে যায়');
  assert.equal(linked.id,first.id);
  assert.equal(linked.action,'linked');
  assert.ok(store.update(first.id,{status:'resolved'}).error);
  store.update(first.id,{status:'working',note:'Diagnosis started'});
  store.update(first.id,{status:'resolved',note:'Replaced the cable'});
  const recurrence=issue(store,'last row seat 5 off hoy');
  assert.equal(recurrence.id,first.id);
  assert.equal(recurrence.action,'reopened');
  const result=store.detail(first.id);
  assert.equal(result.repeats,1);
  assert.equal(result.reports.length,3);
  assert.ok(result.events.some(event=>event.note==='Replaced the cable'));
});
test('different labs or faults stay distinct and old repairs start a new incident',t=>{
  const store=fixture(t);
  const date=Date.now()-40*86400_000;
  const first=issue(store,'PC 3 screen blank',{},date);
  store.update(first.id,{status:'resolved',note:'New cable'},date+60000);
  const again=issue(store,'PC 3 screen blank');
  assert.notEqual(again.id,first.id);
  assert.notEqual(issue(store,'PC 3 screen blank',{lab:'systems'}).id,again.id);
  assert.notEqual(issue(store,'PC 3 mouse cursor broken').id,again.id);
});
test('review merge preserves original reports and idempotent retry IDs',t=>{
  const store=fixture(t);
  const first=issue(store,'PC 3 screen blank');
  const report=issue(store,'screen blank near the wall',{key:'test-retry-key-00001'});
  assert.equal(report.action,'review');
  assert.equal(issue(store,'screen blank near the wall',{key:'test-retry-key-00001'}).report,report.report);
  assert.equal(store.merge(report.id,first.id).id,first.id);
  assert.equal(store.detail(first.id).reports.length,2);
  assert.equal(store.detail(report.id),null);
  assert.equal(issue(store,'screen blank near the wall',{key:'test-retry-key-00001'}).id,first.id);
  assert.ok(issue(store,'mouse broken').id>report.id);
});
test('incidents persist after a new database connection',t=>{
  const folder=mkdtempSync(join(tmpdir(),'labfix-test-'));
  const path=join(folder,'persistent.sqlite');
  try {
    const first=openStore(path);
    const {id}=issue(first,'PC 2 monitor blank');
    first.setAvailability('innovation','PC-02',true,'Awaiting a monitor replacement',1);
    first.setAvailability('innovation','PC-02',false,'Replacement verified',2);
    const saved=first.addRunbook('innovation',{fault:'display',title:'Monitor repair reference',keywords:'monitor',
      summary:'Check connections before requesting replacement.',checks:['Record the indicator state.','Confirm the correct display input.']},3);
    first.close();
    const second=openStore(path);
    assert.equal(second.detail(id).asset,'PC-02');
    assert.deepEqual(second.workstationHistory('innovation','PC-02').map(row=>row.offline),[0,1]);
    assert.deepEqual(second.workstationHistory('systems','PC-02'),[]);
    assert.equal(second.publishedRunbooks()[0].id,saved.id);
    second.setRunbookArchive('innovation',saved.id,true,4);
    assert.deepEqual(second.publishedRunbooks(),[]);
    assert.equal(second.archivedRunbooks('innovation')[0].archived,4);
    second.close();
  } finally {rmSync(folder,{recursive:true,force:true});}
});
test('first-response deadline and revision follow the current repair cycle',t=>{
  const store=fixture(t);
  const start=Date.UTC(2026,10,24,8);
  const hour=3600_000;
  const {id}=issue(store,'PC 3 monitor shows no signal',{},start);
  const opened=store.detail(id);
  const urgent=store.update(id,{status:'open',priority:'urgent',revision:opened.revision},start+hour);
  assert.equal(urgent.response_due,start+2*hour);
  assert.equal(store.metrics('innovation',start+2*hour-1).overdue,0);
  assert.equal(store.metrics('innovation',start+2*hour).overdue,1);
  assert.match(store.update(id,{status:'working',revision:opened.revision},start+2*hour).error,/changed/);
  const working=store.update(id,{status:'working',revision:urgent.revision},start+3*hour);
  assert.equal(working.first_response,start+3*hour);
  assert.equal(store.metrics('innovation',start+4*hour).overdue,0);
  store.update(id,{status:'resolved',note:'New monitor fitted'},start+5*hour);
  assert.equal(store.detail(id).first_response,working.first_response);
  assert.equal(issue(store,'PC 3 monitor shows no signal',{},start+6*hour).action,'reopened');
  assert.equal(store.detail(id).first_response,null);
  assert.equal(store.detail(id).response_due,start+8*hour);
  assert.equal(store.metrics('innovation',start+8*hour).overdue,1);
});
test('earlier databases recover the current response cycle from the event log',t=>{
  const folder=mkdtempSync(join(tmpdir(),'labfix-migrate-'));
  const path=join(folder,'legacy.sqlite');
  try {
    const old=new DatabaseSync(path);
    old.exec(`
      CREATE TABLE incidents(id INTEGER PRIMARY KEY AUTOINCREMENT, lab TEXT, asset TEXT, fault TEXT,
        status TEXT, created INTEGER, updated INTEGER, resolved INTEGER, repeats INTEGER);
      CREATE TABLE events(id INTEGER PRIMARY KEY, incident INTEGER, type TEXT, note TEXT, created INTEGER);
      INSERT INTO incidents VALUES(1,'innovation','PC-03','display','open',100,300,NULL,1);
      INSERT INTO events VALUES(1,1,'created','Report received',100),(2,1,'working','Investigated',150),
        (3,1,'resolved','New cable',200),(4,1,'reopened','Returned after repair',300);
      INSERT INTO incidents VALUES(2,'innovation','PC-02','power','working',400,500,NULL,0);
      INSERT INTO events VALUES(5,2,'created','Report received',400),(6,2,'working','Investigated',500);
    `);
    old.close();
    const store=openStore(path);
    assert.equal(store.detail(1).cycle_started,300);
    assert.equal(store.detail(1).first_response,null);
    assert.equal(store.detail(2).first_response,500);
    store.close();
  } finally {rmSync(folder,{recursive:true,force:true});}
});
